# Description: Generates rtl/sanity/ from the golden RTL with one deliberate bug (result lane 0 is +1).
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "rtl", "sb_systolic_array.sv")
DST = os.path.join(ROOT, "rtl", "sanity")
ANCHOR = "      push_data[n*ACC_W +: ACC_W] = (cfg_relu && col_out[n] < 0) ? '0 : col_out[n];\n"
BUG = "    push_data[0 +: ACC_W] = push_data[0 +: ACC_W] + 1;   // sanity bug: lane 0 off by one\n"
HEADER = ("// File:        sb_systolic_array.sv\n"
          "// Author:      Isaac Hagedorn\n"
          "// Date:        2026-02-14\n"
          "// Description: Golden design with one deliberate bug (result lane 0 is +1). Generated by scripts/make_sanity_rtl.py.\n")


def strip_header(text):
    """Drops the golden file's File/Author/Date/Description lines."""
    lines = text.splitlines(keepends=True)
    while lines and lines[0].startswith(("// File:", "// Author:", "// Date:", "// Description:")):
        lines.pop(0)
    return "".join(lines)


text = strip_header(open(SRC, encoding="utf-8").read())
assert text.count(ANCHOR) == 1, "anchor line changed in rtl/sb_systolic_array.sv"
loop_end = text.index("  end\n", text.index(ANCHOR) + len(ANCHOR))   # end of the ReLU always_comb
text = text[:loop_end] + BUG + text[loop_end:]

os.makedirs(DST, exist_ok=True)
with open(os.path.join(DST, "sb_systolic_array.sv"), "w", encoding="utf-8") as fh:
    fh.write(HEADER + text)
with open(os.path.join(DST, "sanity.f"), "w", encoding="utf-8") as fh:
    fh.write("// File:        sanity.f\n// Author:      Isaac Hagedorn\n// Date:        2026-02-14\n"
             "// Description: Sanity-bug RTL file list. Paths are relative to this file.\n"
             "../sb_sa_pe.sv\n../sb_sa_fifo.sv\nsb_systolic_array.sv\n")
print("wrote rtl/sanity/")
