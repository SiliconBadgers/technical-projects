# Description: Generates rtl/sanity/ from the golden RTL with one deliberate bug (every entry is read out as its value + 1).
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "rtl", "sb_fifo.sv")
DST = os.path.join(ROOT, "rtl", "sanity")
ANCHOR = "  assign out_data     = mem[rd_ptr];\n"
BUG = "  assign out_data     = mem[rd_ptr] + 1'b1;   // sanity bug: read data off by one\n"
HEADER = ("// File:        sb_fifo.sv\n"
          "// Author:      Isaac Hagedorn\n"
          "// Date:        2026-10-08\n"
          "// Description: Golden design with one deliberate bug (out_data is the entry + 1). Generated by scripts/make_sanity_rtl.py.\n")


def strip_header(text):
    """Drops the golden file's File/Author/Date/Description lines."""
    lines = text.splitlines(keepends=True)
    while lines and lines[0].startswith(("// File:", "// Author:", "// Date:", "// Description:")):
        lines.pop(0)
    return "".join(lines)


text = strip_header(open(SRC, encoding="utf-8").read())
assert text.count(ANCHOR) == 1, "anchor line changed in rtl/sb_fifo.sv"
text = text.replace(ANCHOR, BUG)

os.makedirs(DST, exist_ok=True)
with open(os.path.join(DST, "sb_fifo.sv"), "w", encoding="utf-8") as fh:
    fh.write(HEADER + text)
with open(os.path.join(DST, "sanity.f"), "w", encoding="utf-8") as fh:
    fh.write("// File:        sanity.f\n// Author:      Isaac Hagedorn\n// Date:        2026-10-08\n"
             "// Description: Sanity-bug RTL file list. Paths are relative to this file.\n"
             "sb_fifo.sv\n")
print("wrote rtl/sanity/")
