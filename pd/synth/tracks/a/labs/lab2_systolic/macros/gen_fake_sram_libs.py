#!/usr/bin/env python3
# File:        gen_fake_sram_libs.py
# Author:      Isaac Hagedorn
# Date:        2026-10-08
# Description: Generates the fake Liberty timing models of sb_sram_256x8 per platform and corner. Fake timing for training only.

from pathlib import Path

HERE = Path(__file__).resolve().parent
CELL = "sb_sram_256x8"

# Typical-corner numbers per process family (ns, pF, um^2, nW).
FAMILY = {
    "sky130": dict(clk2q=0.80, setup=0.25, hold=0.05, slew=0.10, cap=0.005, area=21000.0, leak=500.0,
                   min_period=1.6, corners={"tt": (1.80, 25), "ss": (1.60, 100), "ff": (1.95, -40)}),
    "gf180": dict(clk2q=2.00, setup=0.60, hold=0.10, slew=0.30, cap=0.010, area=62000.0, leak=900.0,
                  min_period=4.0, corners={"tt": (5.00, 25), "ss": (4.50, 125), "ff": (5.50, -40)}),
}
# Delay multipliers per corner.
SCALE = {"sky130": {"tt": 1.0, "ss": 1.9, "ff": 0.6}, "gf180": {"tt": 1.0, "ss": 1.6, "ff": 0.65}}
PLATFORMS = {"sky130hd": "sky130", "sky130hs": "sky130", "sky130scl": "sky130",
             "gf180_7t": "gf180", "gf180_9t": "gf180"}


def scalar(name: str, value: float) -> str:
    return f'{name} (scalar) {{ values ("{value:.4f}"); }}'


def constraint_pin(kind: str, pin: str, f: dict, s: float, bus: bool) -> str:
    head = f'bus ({pin}) {{\n      bus_type : bus8;' if bus else f'pin ({pin}) {{'
    return f"""    {head}
      direction : input;
      capacitance : {f['cap']:.4f};
      timing () {{
        related_pin : "clk";
        timing_type : setup_rising;
        {scalar('rise_constraint', f['setup'] * s)}
        {scalar('fall_constraint', f['setup'] * s)}
      }}
      timing () {{
        related_pin : "clk";
        timing_type : hold_rising;
        {scalar('rise_constraint', f['hold'] * s)}
        {scalar('fall_constraint', f['hold'] * s)}
      }}
    }}"""


def lib(platform: str, corner: str) -> str:
    fam = PLATFORMS[platform]
    f = FAMILY[fam]
    s = SCALE[fam][corner]
    volt, temp = f["corners"][corner]
    name = f"{CELL}_{platform}_{corner}"
    return f"""/* ==========================================================================
 * {name}.lib
 *
 * FAKE TIMING MODEL FOR TRAINING ONLY.
 * There is no real SRAM behind this file. The numbers are made up (scaled
 * from rough {fam} estimates) so synthesis and STA can treat the macro like
 * a real one. Generated by gen_fake_sram_libs.py -- edit that, not this.
 * ========================================================================== */
library ({name}) {{
  technology (cmos);
  delay_model : table_lookup;
  time_unit : "1ns";
  voltage_unit : "1V";
  current_unit : "1mA";
  leakage_power_unit : "1nW";
  capacitive_load_unit (1, pf);
  pulling_resistance_unit : "1kohm";
  nom_process : 1;
  nom_voltage : {volt:.2f};
  nom_temperature : {temp};
  default_max_transition : {f['slew'] * s * 10:.3f};
  input_threshold_pct_rise : 50;
  input_threshold_pct_fall : 50;
  output_threshold_pct_rise : 50;
  output_threshold_pct_fall : 50;
  slew_lower_threshold_pct_rise : 20;
  slew_lower_threshold_pct_fall : 20;
  slew_upper_threshold_pct_rise : 80;
  slew_upper_threshold_pct_fall : 80;

  type (bus8) {{
    base_type : array;
    data_type : bit;
    bit_width : 8;
    bit_from : 7;
    bit_to : 0;
    downto : true;
  }}

  cell ({CELL}) {{
    area : {f['area']:.1f};
    cell_leakage_power : {f['leak'] * (3.0 if corner == 'ss' else 1.0):.1f};
    dont_touch : true;
    dont_use : true;
    interface_timing : true;

    pin (clk) {{
      direction : input;
      capacitance : {f['cap'] * 2:.4f};
      clock : true;
      min_period : {f['min_period'] * s:.3f};
    }}
{constraint_pin('setup', 'ce_in', f, s, False)}
{constraint_pin('setup', 'we_in', f, s, False)}
{constraint_pin('setup', 'addr_in', f, s, True)}
{constraint_pin('setup', 'wd_in', f, s, True)}
    bus (rd_out) {{
      bus_type : bus8;
      direction : output;
      max_capacitance : {f['cap'] * 40:.3f};
      timing () {{
        related_pin : "clk";
        timing_type : rising_edge;
        timing_sense : non_unate;
        {scalar('cell_rise', f['clk2q'] * s)}
        {scalar('cell_fall', f['clk2q'] * s)}
        {scalar('rise_transition', f['slew'] * s)}
        {scalar('fall_transition', f['slew'] * s)}
      }}
    }}
  }}
}}
"""


def main() -> None:
    for platform in PLATFORMS:
        for corner in ("tt", "ss", "ff"):
            path = HERE / f"{CELL}_{platform}_{corner}.lib"
            path.write_text(lib(platform, corner))
            print(f"wrote {path.name}")


if __name__ == "__main__":
    main()
